import { readFileSync, readdirSync } from "node:fs";
import { join } from "node:path";

export function parseFrontmatter(md) {
  if (!md.startsWith("---\n")) return { attrs: {}, body: md };
  const end = md.indexOf("\n---\n", 4);
  if (end === -1) return { attrs: {}, body: md };
  const attrs = {};
  for (const line of md.slice(4, end).split("\n")) {
    const m = line.match(/^([A-Za-z0-9_-]+):\s*(.*)$/);
    if (m) attrs[m[1]] = m[2].trim();
  }
  return { attrs, body: md.slice(end + 5) };
}

export const HARNESS_BEGIN = "<!-- harness:begin -->";
export const HARNESS_END = "<!-- harness:end -->";

export const OPENCODE_BLOCK = `## OpenCode Specifics

<!-- harness-specific section: generated by adapters/opencode/transform.js -->
- Spawn specialists with the \`task\` tool (\`subagent_type\` = roster name); recon via \`task\` with \`subagent_type: "general"\` (2–5 in parallel, one angle each) or your own Read/Grep/Glob.
- External knowledge (unfamiliar libraries, API docs) comes from \`webfetch\`/\`websearch\` — never from memory.
- Track work with \`todowrite\`; ask the user questions directly in your reply, one at a time — there is no question tool.
- Brain loading, the write jail, and the run ledger are enforced by the NEO plugin. The stop-gate is advisory here: it nudges once, it cannot block the turn.
- Verify edits with project linters/tests via \`bash\`; prefer project-defined commands from AGENTS.md.
`;

export function swapHarnessBlock(body, replacement) {
  const b = body.indexOf(HARNESS_BEGIN);
  const e = body.indexOf(HARNESS_END);
  if (b === -1 || e === -1 || e < b) return body;
  return body.slice(0, b) + replacement + body.slice(e + HARNESS_END.length);
}

export function transformAgent(name, md, { permissions, models }) {
  const { attrs, body } = parseFrontmatter(md);
  const agent = {
    description: attrs.description ?? "",
    mode: name === "neo" ? "primary" : "subagent",
    prompt: name === "neo" ? swapHarnessBlock(body, OPENCODE_BLOCK) : body,
  };
  const model = attrs.model && attrs.model !== "inherit" ? models[attrs.model] : undefined;
  if (model) agent.model = model;
  const permission = permissions[name];
  if (permission && Object.keys(permission).length) agent.permission = permission;
  return agent;
}

export function transformSkill(name, md, { pluginRoot }) {
  const { attrs, body } = parseFrontmatter(md);
  const template = body
    .replaceAll("${CLAUDE_PLUGIN_ROOT}", pluginRoot)
    .replace(/\bAgent tool\b/g, "task tool");
  return { description: attrs.description ?? "", agent: "neo", template };
}

export function buildConfig({ agentsDir, skillsDir, pluginRoot, permissions, models }) {
  const agent = {};
  for (const f of readdirSync(agentsDir).filter((f) => f.endsWith(".md")).sort()) {
    const name = f.slice(0, -3);
    agent[name] = transformAgent(name, readFileSync(join(agentsDir, f), "utf8"), { permissions, models });
  }
  const command = {};
  for (const d of readdirSync(skillsDir).sort()) {
    let md;
    try {
      md = readFileSync(join(skillsDir, d, "SKILL.md"), "utf8");
    } catch {
      continue;
    }
    command[`neo:${d}`] = transformSkill(d, md, { pluginRoot });
  }
  return { agent, command };
}
